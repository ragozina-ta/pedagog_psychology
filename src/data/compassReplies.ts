let replyCursor = 0

export function nextCompassReply(): CompassReply {
  const item = COMPASS_REPLIES[replyCursor % COMPASS_REPLIES.length]
  replyCursor += 1
  return item
}

export function pickCompassReply(seed?: string): CompassReply {
  if (!seed) return nextCompassReply()
  let h = 0
  for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0
  return COMPASS_REPLIES[h % COMPASS_REPLIES.length]
}

