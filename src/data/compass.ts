const CRISIS_KEYWORDS = [
  'суицид',
  'убить себя',
  'не хочу жить',
  'покончить',
  'самоубий',
  'насилие',
  'избива',
  'угрожа',
  'мне страшно за жизнь',
]

const ANXIETY_KEYWORDS = ['тревог', 'паник', 'сердце колотится', 'не могу дышать', 'страшно']
const BURNOUT_KEYWORDS = ['выгоран', 'нет сил', 'истощен', 'выжат', 'не могу больше']
const CONFLICT_KEYWORDS = ['конфликт', 'родитель', 'директор', 'коллега', 'скандал']
const KIDS_KEYWORDS = ['ученик', 'класс', 'дети', 'ребёнок', 'ребенок']

export function detectCrisis(text: string): boolean {
  const t = text.toLowerCase()
  return CRISIS_KEYWORDS.some((k) => t.includes(k))
}

export function localCompassReply(userText: string): string {
  const t = userText.toLowerCase()

  if (detectCrisis(userText)) {
    return [
      'Мне важно ваше состояние. Если есть угроза жизни или безопасности — это уже не то, что нужно проживать в одиночку.',
      '',
      'Сделайте, пожалуйста, одно из действий прямо сейчас:',
      '• обратитесь к близкому человеку, который рядом;',
      '• свяжитесь с администрацией школы / службой психологической помощи;',
      '• при угрозе насилия или опасности — в полицию / экстренные службы (112).',
      '',
      'Я могу быть рядом словами поддержки, но срочная безопасность важнее разговора. Вы не обязаны справляться в одиночку.',
    ].join('\n')
  }

  if (ANXIETY_KEYWORDS.some((k) => t.includes(k))) {
    return [
      'Слышу тревогу. Давайте замедлимся на минуту.',
      '',
      'Техника прямо сейчас:',
      '1) Положите ноги на пол, почувствуйте опору.',
      '2) Вдох на 4, выдох на 6 — 5 циклов.',
      '3) Назовите 3 предмета вокруг и их цвет.',
      '',
      'Тревога часто кричит громче фактов. Что именно сейчас пугает сильнее всего — тело, мысли о будущем или конкретная ситуация?',
    ].join('\n')
  }

  if (BURNOUT_KEYWORDS.some((k) => t.includes(k))) {
    return [
      'Похоже на глубокую усталость, а не на «слабость». Педагогическая отдача без восстановления истощает даже самых сильных.',
      '',
      'Переформулируем: не «я не справляюсь», а «мне нужно восполнение ресурса».',
      '',
      'Микро-шаг на сегодня: выберите одно — вода, 10 минут тишины, короткая прогулка или просьба о помощи. Что из этого реально сделать в ближайший час?',
    ].join('\n')
  }

  if (CONFLICT_KEYWORDS.some((k) => t.includes(k))) {
    return [
      'Конфликт в школе часто бьёт по самооценке. Давайте отделим факты от интерпретаций.',
      '',
      'Попробуйте схему:',
      '• Факт: что произошло без оценок?',
      '• Чувство: что вы чувствуете?',
      '• Потребность: что вам сейчас важно?',
      '• Просьба: о чём можно попросить спокойно?',
      '',
      'Если хотите, опишите ситуацию в 3–4 предложениях — помогу сформулировать мягкий и твёрдый ответ.',
    ].join('\n')
  }

  if (KIDS_KEYWORDS.some((k) => t.includes(k))) {
    return [
      'Контакт с детьми — сердце вашей работы, и он требует энергии. Сложности здесь не делают вас «плохим педагогом».',
      '',
      'Что помогает часто:',
      '• одна тёплая фраза одному ребёнку;',
      '• ясная граница без стыда;',
      '• короткая пауза перед реакцией.',
      '',
      'Расскажите, что сейчас происходит в классе: поведение, атмосфера или ваше внутреннее состояние?',
    ].join('\n')
  }

  return [
    'Я рядом. Можно говорить честно — без нужды звучать «правильно».',
    '',
    'Давайте чуть проясним:',
    '1) Что произошло?',
    '2) Что вы чувствуете в теле и эмоциях?',
    '3) Что бы сейчас стало хоть немного легче?',
    '',
    'Могу предложить технику самопомощи, помочь переформулировать проблему или просто побыть с вами в этом. Что нужнее сейчас?',
  ].join('\n')
}

