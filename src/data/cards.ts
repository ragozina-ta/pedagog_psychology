export const DAILY_CARDS: DailyCard[] = PACK.flatMap(([category, tasks]) =>
  tasks.map((task, i) => ({
    id: `${category}-${i + 1}`,
    title: TITLES[category][i] || `Карточка ${i + 1}`,
    task,
    category,
  })),
)

export function cardForDate(date = new Date()): DailyCard {
  return deviceDailyPick('home-card', DAILY_CARDS, (c) => c.id, date)
}

export function cardsForCategories(categories: string[], limit = 3): DailyCard[] {
  const pool = DAILY_CARDS.filter((c) => categories.includes(c.category))
  return pool.slice(0, limit)
}
